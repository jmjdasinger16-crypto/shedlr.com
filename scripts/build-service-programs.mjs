import fs from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { categoryLabels, groups, programs } from "../worker/src/category-programs.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const read = name => fs.readFileSync(path.join(root, name), "utf8");
const touch = (name, value) => {
  const file = path.join(root, name);
  if (fs.existsSync(file) && read(name) === value) return;
  if (check) {
    console.error(`Out of date: ${name}. Run npm run build:programs.`);
    process.exitCode = 1;
  } else fs.writeFileSync(file, value);
};

